-- 4. Deduplication & Integrity Guard on Reconciliation Reviews
-- Prevents duplicate PENDING_REVIEW items from ever accumulating for the same event and discrepancy
CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_pending_ca_review
ON corporate_action_reconciliation_reviews (event_id, discrepancy_field, official_claim_value)
WHERE (review_status = 'PENDING_REVIEW');

-- 5. Hard Database Guard against Test Contamination on Application DB
CREATE OR REPLACE FUNCTION fn_app_db_test_contamination_guard()
RETURNS trigger AS $$
BEGIN
    IF current_database() = 'halal_equity' THEN
        -- Check for obvious test identifiers
        IF NEW.source_url LIKE '%spoofed-exchange%' OR NEW.source_url LIKE '%unauthorized-domain%' OR NEW.source_url LIKE '%vendor-api.thirdparty%' THEN
            RAISE EXCEPTION 'HARD DATABASE GUARD: Insertion of adversarial test fixtures is prohibited on application database halal_equity (target halal_equity_test instead)';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_app_db_ca_artifact_guard ON corporate_action_source_artifacts;
CREATE TRIGGER trg_app_db_ca_artifact_guard
BEFORE INSERT ON corporate_action_source_artifacts
FOR EACH ROW EXECUTE FUNCTION fn_app_db_test_contamination_guard();

DROP TRIGGER IF EXISTS trg_app_db_fin_artifact_guard ON financial_disclosure_source_artifacts;
